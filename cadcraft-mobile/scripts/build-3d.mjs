// Bundles web3d/engine.ts (three.js + Manifold WASM) into one self-contained HTML string so the
// 3D modeler works offline inside react-native-webview. Run: npm run build:3d
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';

const wasm = readFileSync('node_modules/manifold-3d/manifold.wasm').toString('base64');
const out = await build({
  entryPoints: ['web3d/engine.ts'],
  bundle: true, minify: true, write: false, format: 'iife', platform: 'browser', target: 'es2020',
  define: { WASM_BASE64: JSON.stringify(wasm), 'import.meta.url': '"file:///"' },
  external: ['node:*'],
  logLevel: 'warning',
});
const js = out.outputFiles[0].text.replace(/<\/script/g, '<\\/script');
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no"><style>html,body{margin:0;height:100%;overflow:hidden;background:#0b1120;touch-action:none}canvas{display:block}</style></head><body><script>${js}</script></body></html>`;
writeFileSync('web3d/engine.html', html);
writeFileSync('src/engine3d.generated.ts', `// Generated by scripts/build-3d.mjs — do not edit.\nexport const ENGINE_HTML = ${JSON.stringify(html)};\n`);
console.log(`engine3d: ${(html.length / 1024).toFixed(0)} KB`);
